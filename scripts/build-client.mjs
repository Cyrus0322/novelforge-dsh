// 把 src/client 编译成 DSH 客户端插件 bundle：lib/client.js
// 格式与官方客户端插件一致：window.__ModuleLoader__.load({ id, factory })
// React 等基座模块保持 external，由宿主提供；其余代码全部内联。
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))

const result = await build({
  entryPoints: [resolve(root, 'src/client/index.tsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  jsxImportSource: 'react',
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  legalComments: 'none',
  charset: 'utf8',
  logLevel: 'warning',
})

const body = result.outputFiles[0].text
const wrapped = `// @generated by scripts/build-client.mjs —— 不要手改，改 src/client/*
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${body.split('\n').map(line => (line ? `    ${line}` : line)).join('\n')}
    return module.exports;
  }
});
`

const outFile = resolve(root, 'lib/client.js')
mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, wrapped, 'utf8')
console.log(`[build-client] ${outFile} (${(wrapped.length / 1024).toFixed(1)} KB)`)
